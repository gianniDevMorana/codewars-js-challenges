function arrayMadness(a, b) {
  let sumOfSquares = 0;
  let sumOfCubes = 0;
  for (let i = 0; i < a.length; i++) {
    sumOfSquares += a[i] ** 2;
  }
  for (let i = 0; i < b.length; i++) {
    sumOfCubes += b[i] ** 3;
  }
  return sumOfSquares > sumOfCubes;
}

console.log(arrayMadness([4, 5, 6], [1, 2, 3]));
console.log(arrayMadness([5, 6, 7], [4, 5, 6]));
